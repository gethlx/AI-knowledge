pairs = []
with open(PAIRS, encoding="utf-8") as f:
    for line in f:
        line = line.strip()
        if line:
            pairs.append(json.loads(line)["pair_id"])

missing = [p for p in pairs if p not in J]
extra = [p for p in J if p not in set(pairs)]
if missing or extra:
    print("MISSING:", missing)
    print("EXTRA:", extra)
    sys_exit = 1
    raise SystemExit(f"清单不一致: 缺 {len(missing)} 对, 多 {len(extra)} 对")

errors = []
for pid in pairs:
    rel, evs, reason, conf = J[pid]
    a, b = pid.split("__")
    if rel == "prerequisite":
        pass  # 本批无
    # direction 规则
    # 每对两卡各至少 1 条证据
    ev_cards = {e["card_id"] for e in evs}
    if ev_cards != {a, b}:
        errors.append(f"{pid}: 证据卡不覆盖两卡 {ev_cards}")
    for e in evs:
        field_text = cards.get(e["card_id"], {}).get(e["field"])
        if field_text is None:
            errors.append(f"{pid}: 卡/字段不存在 {e['card_id']}/{e['field']}")
        elif e["quote"] not in field_text:
            errors.append(f"{pid}: quote 未逐字命中 {e['card_id']}/{e['field']}: {e['quote'][:30]}...")
    if rel not in ("prerequisite", "related", "no_relation", "insufficient_evidence"):
        errors.append(f"{pid}: 非法 relation_type {rel}")
    if not (0 <= conf <= 1):
        errors.append(f"{pid}: confidence 越界")
    if "前置概念" in reason or "后续概念" in reason:
        errors.append(f"{pid}: reason 引用作废字段")

if errors:
    print("\n".join(errors))
    raise SystemExit(f"校验失败 {len(errors)} 处")

