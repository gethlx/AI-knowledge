# ---------- 校验与落盘 ----------
errors = []
written = 0
for pid in pairs:
    if pid not in J:
        errors.append((pid, "missing judgment"))
        continue
    j = J[pid]
    a, b = pid.split("__")
    rt, dr = j["relation_type"], j["direction"]
    if rt not in ("prerequisite", "related", "no_relation", "insufficient_evidence"):
        errors.append((pid, "bad relation_type"))
    if rt == "prerequisite" and dr not in ("source_to_target", "target_to_source"):
        errors.append((pid, "prerequisite without direction"))
    if rt != "prerequisite" and dr is not None:
        errors.append((pid, "direction must be null"))
    ev_cards = [e["card_id"] for e in j["evidence"]]
    if sorted(ev_cards) != sorted([a, b]) or len(ev_cards) != 2:
        errors.append((pid, f"evidence must cover both cards exactly: {ev_cards}"))
    for e in j["evidence"]:
        sec = sections.get(e["card_id"], "")
        if not sec:
            errors.append((pid, f"card {e['card_id']} not in snapshot"))
        elif e["quote"] not in sec:
            errors.append((pid, f"quote not verbatim in card {e['card_id']}: {e['quote'][:30]}..."))
    if errors and errors[-1][0] == pid:
        continue
    obj = {
        "pair_id": pid,
        "reviewer_id": REVIEWER,
        "model_requested": MODEL,
        "model_returned": MODEL,
        "relation_type": rt,
        "direction": dr,
        "evidence": j["evidence"],
        "reason": j["reason"],
        "confidence": j["confidence"],
        "input_card_hash": "PENDING",
        "prompt_hash": "PENDING",
        "status": "REVIEW_COMPLETED",
    }
    d = os.path.join(OUT, pid)
    os.makedirs(d, exist_ok=True)
    fp = os.path.join(d, f"{REVIEWER}.json")
    with open(fp, "w", encoding="utf-8") as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)
    written += 1

# 回读校验 JSON 可解析
